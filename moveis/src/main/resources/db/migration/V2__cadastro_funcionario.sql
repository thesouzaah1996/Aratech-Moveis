CREATE TABLE IF NOT EXISTS funcionario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo BOOLEAN DEFAULT TRUE,
    nome_completo VARCHAR(150),
    cpf VARCHAR(255),
    rg VARCHAR(20),
    pis_nit_nis VARCHAR(255),
    data_nascimento DATE,
    sexo SMALLINT,
    estado_civil SMALLINT,
    nome_mae VARCHAR(150),
    nome_pai VARCHAR(150),
    cep VARCHAR(255),
    logradouro VARCHAR(150),
    numero VARCHAR(15),
    complemento VARCHAR(100),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    uf SMALLINT,
    telefone_fixo VARCHAR(255),
    celular_whatsapp VARCHAR(255),
    data_admissao DATE,
    tipo_contrato VARCHAR(255),
    jornada_semanal INTEGER,
    cargo VARCHAR(100),
    tipo_funcionario VARCHAR(255),
    setor VARCHAR(100),
    salario NUMERIC(12, 2),
    email VARCHAR(150),
    banco VARCHAR(100),
    agencia VARCHAR(255),
    conta VARCHAR(255),
    tipo_conta VARCHAR(255),
    chave_pix VARCHAR(150)
);

-- As restrições também protegem contra cadastros concorrentes.
CREATE UNIQUE INDEX IF NOT EXISTS uk_funcionario_cpf ON funcionario (cpf);
CREATE UNIQUE INDEX IF NOT EXISTS uk_funcionario_email ON funcionario (LOWER(email));
CREATE UNIQUE INDEX IF NOT EXISTS uk_funcionario_pis ON funcionario (pis_nit_nis);

CREATE TABLE IF NOT EXISTS funcionario_documento (
    funcionario_id BIGINT NOT NULL REFERENCES funcionario (id),
    tipo VARCHAR(255) NOT NULL,
    objeto VARCHAR(255) NOT NULL,
    PRIMARY KEY (funcionario_id, tipo)
);
