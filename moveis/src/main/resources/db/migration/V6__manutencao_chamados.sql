     AND finalidade IS NOT NULL AND finalidade IN ('CORRETIVA','PREVENTIVA','MELHORIA','ESTOQUE')));

CREATE TABLE IF NOT EXISTS manutencao_mecanico (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL CHECK (char_length(btrim(nome)) BETWEEN 3 AND 150),
 turno VARCHAR(10) NOT NULL CHECK (turno IN ('MANHA','TARDE','NOITE')),
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS manutencao_mecanico_especialidade (
 mecanico_id BIGINT NOT NULL REFERENCES manutencao_mecanico(id),
 especialidade VARCHAR(25) NOT NULL CHECK (especialidade IN ('SECCIONADORA','BORDEADEIRA','CNC','PRENSA','FURADEIRA','LIXADEIRA','TUPIA','SERRA_CIRCULAR','COLADEIRA','PANTOGRAFO','ENVERNIZADEIRA','COMPRESSOR')),
 PRIMARY KEY(mecanico_id,especialidade)
);
ALTER TABLE manutencao_chamado ADD COLUMN IF NOT EXISTS mecanico_id BIGINT REFERENCES manutencao_mecanico(id);
ALTER TABLE manutencao_chamado ADD COLUMN IF NOT EXISTS data_inicio TIMESTAMPTZ;
ALTER TABLE manutencao_chamado ADD COLUMN IF NOT EXISTS data_conclusao TIMESTAMPTZ;
ALTER TABLE manutencao_chamado DROP CONSTRAINT IF EXISTS ck_manutencao_horarios;
