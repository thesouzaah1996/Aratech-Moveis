CREATE TABLE IF NOT EXISTS manutencao_chamado (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 equipamento VARCHAR(150) NOT NULL,
 tipo VARCHAR(15) NOT NULL,
 prioridade VARCHAR(10) NOT NULL,
 solicitante VARCHAR(150) NOT NULL,
 setor VARCHAR(100) NOT NULL,
 telefone VARCHAR(11),
 descricao VARCHAR(3000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'ABERTA',
 data_abertura TIMESTAMPTZ NOT NULL,
 chave_operacao UUID NOT NULL UNIQUE,
 CONSTRAINT ck_manutencao_equipamento CHECK (char_length(btrim(equipamento)) BETWEEN 2 AND 150),
 CONSTRAINT ck_manutencao_solicitante CHECK (char_length(btrim(solicitante)) BETWEEN 3 AND 150),
 CONSTRAINT ck_manutencao_setor CHECK (char_length(btrim(setor)) BETWEEN 2 AND 100),
 CONSTRAINT ck_manutencao_descricao CHECK (char_length(btrim(descricao)) BETWEEN 3 AND 3000),
 CONSTRAINT ck_manutencao_tipo CHECK (tipo IN ('CORRETIVA','PREVENTIVA')),
 CONSTRAINT ck_manutencao_prioridade CHECK (prioridade IN ('BAIXA','MEDIA','ALTA')),
 CONSTRAINT ck_manutencao_status CHECK (status IN ('ABERTA','EM_MANUTENCAO','CONCLUIDA')),
 CONSTRAINT ck_manutencao_telefone CHECK (telefone IS NULL OR telefone='' OR telefone ~ '^[1-9][0-9]{9,10}$')
);
CREATE INDEX IF NOT EXISTS ix_manutencao_chamado_fila ON manutencao_chamado (status,data_abertura DESC,id DESC);

