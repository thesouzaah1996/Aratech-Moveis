CREATE TABLE IF NOT EXISTS rh_ponto_dia (
    funcionario_id BIGINT NOT NULL REFERENCES funcionario(id),
    data DATE NOT NULL,
    horarios VARCHAR(35) NOT NULL,
    versao BIGINT NOT NULL DEFAULT 1,
    PRIMARY KEY(funcionario_id,data)
);
CREATE TABLE IF NOT EXISTS rh_ponto_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_id BIGINT NOT NULL REFERENCES funcionario(id),
    data DATE NOT NULL,
    anteriores VARCHAR(35) NOT NULL,
    novos VARCHAR(35) NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    autor_id BIGINT NOT NULL,
    autor_nome VARCHAR(150) NOT NULL,
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_ponto_historico_dia ON rh_ponto_historico(funcionario_id,data,id);
