CREATE TABLE fabricacao_setor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(40) NOT NULL UNIQUE, nome VARCHAR(100) NOT NULL,
 recurso VARCHAR(80) NOT NULL UNIQUE, caminho VARCHAR(100) NOT NULL UNIQUE,
 natureza VARCHAR(20) NOT NULL CHECK(natureza IN ('OPERACAO','SEPARACAO')),
 exige_medidas BOOLEAN NOT NULL DEFAULT FALSE
);
