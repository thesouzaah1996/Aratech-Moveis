CREATE TABLE fabricacao_variante (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 modelo_id BIGINT NOT NULL REFERENCES fabricacao_modelo(id),
 codigo VARCHAR(60) NOT NULL, nome VARCHAR(100) NOT NULL,
 ativo BOOLEAN NOT NULL, versao BIGINT NOT NULL DEFAULT 1,
 dados JSONB NOT NULL,
 UNIQUE(modelo_id,codigo)
);
CREATE TABLE pcp_lote_producao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 variante_id BIGINT NOT NULL REFERENCES fabricacao_variante(id),
 revisao BIGINT NOT NULL,
 ordem_origem_id BIGINT REFERENCES pcp_ordem(id),
 quantidade INTEGER NOT NULL CHECK(quantidade BETWEEN 1 AND 10000),
 previsao DATE NOT NULL,
 observacoes VARCHAR(1000) NOT NULL DEFAULT '',
 snapshot JSONB NOT NULL,
 calculo JSONB NOT NULL,
 chave_operacao UUID NOT NULL UNIQUE,
 autor_nome VARCHAR(150) NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_pcp_lote_origem ON pcp_lote_producao(ordem_origem_id);
CREATE TABLE pcp_ordem_setor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lote_id BIGINT NOT NULL REFERENCES pcp_lote_producao(id),
 setor_id BIGINT NOT NULL REFERENCES fabricacao_setor(id),
 status VARCHAR(20) NOT NULL DEFAULT 'LIBERADA' CHECK(status IN ('LIBERADA','EM_ANDAMENTO','CONCLUIDA')),
 versao BIGINT NOT NULL DEFAULT 1,
 dados JSONB NOT NULL,
 liberado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 iniciado_em TIMESTAMPTZ, concluido_em TIMESTAMPTZ,
 UNIQUE(lote_id,setor_id)
);
CREATE INDEX ix_pcp_ordem_setor_fila ON pcp_ordem_setor(setor_id,status,id);
CREATE TABLE pcp_consumo_setor (
 ordem_id BIGINT NOT NULL REFERENCES pcp_ordem_setor(id),
 item_chave UUID NOT NULL,
 produto_id BIGINT NOT NULL REFERENCES produto(id),
 quantidade NUMERIC(16,3) NOT NULL CHECK(quantidade>0),
 chave_operacao UUID NOT NULL UNIQUE,
 confirmado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(ordem_id,item_chave)
);
