CREATE TABLE fabricacao_modelo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    ficha JSONB NOT NULL,
    versao BIGINT NOT NULL DEFAULT 1,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_fabricacao_modelo_codigo ON fabricacao_modelo(lower(codigo));
CREATE TABLE fabricacao_foto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo_id BIGINT NOT NULL REFERENCES fabricacao_modelo(id),
    item_chave UUID,
    legenda VARCHAR(150) NOT NULL DEFAULT '',
    mime VARCHAR(20) NOT NULL CHECK (mime IN ('image/png','image/jpeg')),
    conteudo BYTEA NOT NULL CHECK (octet_length(conteudo) BETWEEN 1 AND 5242880),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_fabricacao_foto_modelo ON fabricacao_foto(modelo_id,ativo);
CREATE TABLE fabricacao_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo_id BIGINT NOT NULL REFERENCES fabricacao_modelo(id),
    modelo_versao BIGINT NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade BETWEEN 1 AND 10000),
    previsao DATE NOT NULL,
    observacoes VARCHAR(1000) NOT NULL DEFAULT '',
    ficha JSONB NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PLANEJADO'
        CHECK (status IN ('PLANEJADO','ENVIADO_CORTE','EM_CORTE','CORTADO','CANCELADO')),
    versao BIGINT NOT NULL DEFAULT 1,
    chave_operacao UUID NOT NULL UNIQUE,
    autor_id BIGINT NOT NULL,
    autor_nome VARCHAR(150) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviado_em TIMESTAMPTZ,
    iniciado_em TIMESTAMPTZ,
    concluido_em TIMESTAMPTZ
);
CREATE INDEX ix_fabricacao_lote_fila ON fabricacao_lote(status,previsao,id);
