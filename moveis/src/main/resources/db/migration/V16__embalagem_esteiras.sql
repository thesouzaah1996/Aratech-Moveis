CREATE TABLE embalagem_esteira (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    atividade VARCHAR(150) NOT NULL,
    responsavel VARCHAR(150) NOT NULL DEFAULT '',
    capacidade INTEGER NOT NULL CHECK(capacidade BETWEEN 1 AND 20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    observacoes VARCHAR(1000) NOT NULL DEFAULT '',
    versao BIGINT NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX uk_embalagem_esteira_codigo ON embalagem_esteira(lower(codigo));
CREATE TABLE embalagem_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem_id BIGINT NOT NULL REFERENCES fabricacao_lote(id),
    ficha JSONB NOT NULL,
    quantidade INTEGER NOT NULL CHECK(quantidade>0),
    previsao DATE NOT NULL,
    prioridade VARCHAR(10) NOT NULL CHECK(prioridade IN ('NORMAL','ALTA','URGENTE')),
    observacoes VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO'
        CHECK(status IN ('AGUARDANDO','EM_EMBALAGEM','PAUSADO','EMBALADO','CANCELADO')),
    versao BIGINT NOT NULL DEFAULT 1,
    volumes INTEGER CHECK(volumes BETWEEN 1 AND 100000),
    chave_operacao UUID NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    concluido_em TIMESTAMPTZ
);
CREATE TABLE embalagem_etapa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES embalagem_lote(id),
    sequencia INTEGER NOT NULL CHECK(sequencia BETWEEN 1 AND 12),
    esteira_id BIGINT NOT NULL REFERENCES embalagem_esteira(id),
    nome VARCHAR(150) NOT NULL,
    instrucoes VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO'
        CHECK(status IN ('AGUARDANDO','EM_EXECUCAO','PAUSADA','CONCLUIDA','CANCELADA')),
    operador VARCHAR(150) NOT NULL DEFAULT '',
    segundos_ativos BIGINT NOT NULL DEFAULT 0 CHECK(segundos_ativos>=0),
    inicio_atual TIMESTAMPTZ,
    iniciado_em TIMESTAMPTZ,
    concluido_em TIMESTAMPTZ,
    motivo_pausa VARCHAR(500) NOT NULL DEFAULT '',
    UNIQUE(lote_id,sequencia)
);
CREATE INDEX ix_embalagem_etapa_esteira ON embalagem_etapa(esteira_id,status,lote_id);
CREATE INDEX ix_embalagem_lote_fila ON embalagem_lote(status,previsao,id);
CREATE UNIQUE INDEX uk_embalagem_lote_origem ON embalagem_lote(origem_id) WHERE status<>'CANCELADO';
CREATE TABLE embalagem_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES embalagem_lote(id),
    etapa_id BIGINT REFERENCES embalagem_etapa(id),
    acao VARCHAR(40) NOT NULL,
    detalhe VARCHAR(1000) NOT NULL DEFAULT '',
    autor VARCHAR(150) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
