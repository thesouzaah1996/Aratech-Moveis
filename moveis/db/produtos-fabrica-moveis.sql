-- Estoque inteiro; saldos so mudam por operacoes transacionais com historico.
CREATE TABLE IF NOT EXISTS produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    sku VARCHAR(64) NOT NULL,
    quantidade INTEGER NOT NULL,
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    fornecedor_id BIGINT NOT NULL REFERENCES fornecedor(id),
    local_armazenamento VARCHAR(100) NOT NULL,
    descricao VARCHAR(2000),
    vencimento_produto TIMESTAMP,
    criado_em TIMESTAMP NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_produto_sku UNIQUE (sku),
    CONSTRAINT ck_produto_sku CHECK (sku ~ '^[A-Z0-9_-]{1,64}$'),
    CONSTRAINT ck_produto_quantidade CHECK (quantidade BETWEEN 0 AND 1000000000),
    CONSTRAINT ck_produto_nome CHECK (char_length(btrim(nome)) BETWEEN 2 AND 150),
    CONSTRAINT ck_produto_local CHECK (char_length(btrim(local_armazenamento)) BETWEEN 2 AND 100),
    CONSTRAINT ck_produto_arquivado CHECK (ativo OR quantidade=0)
);
CREATE TABLE IF NOT EXISTS movimentacao_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produto(id),
    tipo VARCHAR(10) NOT NULL,
    quantidade INTEGER NOT NULL,
    saldo_anterior INTEGER NOT NULL,
    saldo_posterior INTEGER NOT NULL,
    chave_operacao UUID NOT NULL,
    responsavel_id BIGINT,
    responsavel_nome VARCHAR(150) NOT NULL DEFAULT 'Carga de demonstracao',
    motivo VARCHAR(500) NOT NULL DEFAULT 'Saldo inicial de demonstracao',
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_movimentacao_chave UNIQUE (chave_operacao),
    CONSTRAINT ck_movimento_saldos CHECK (saldo_anterior BETWEEN 0 AND 1000000000 AND saldo_posterior BETWEEN 0 AND 1000000000),
    CONSTRAINT ck_movimento_consistencia CHECK (
        (tipo='INICIAL' AND quantidade>=0 AND saldo_anterior=0 AND saldo_posterior=quantidade)
        OR (tipo='ENTRADA' AND quantidade>0 AND saldo_posterior::bigint=saldo_anterior::bigint+quantidade)
        OR (tipo='SAIDA' AND quantidade>0 AND saldo_posterior::bigint=saldo_anterior::bigint-quantidade)
    )
);
CREATE INDEX IF NOT EXISTS ix_produto_categoria ON produto(categoria_id);
CREATE INDEX IF NOT EXISTS ix_produto_fornecedor ON produto(fornecedor_id);
CREATE INDEX IF NOT EXISTS ix_movimento_produto ON movimentacao_estoque(produto_id,id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_movimento_inicial ON movimentacao_estoque(produto_id) WHERE tipo='INICIAL';

