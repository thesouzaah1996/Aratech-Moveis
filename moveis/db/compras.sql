ALTER TABLE produto ADD COLUMN IF NOT EXISTS quantidade_minima INTEGER CHECK (quantidade_minima BETWEEN 0 AND 999999999);
ALTER TABLE manutencao_peca_estoque ADD COLUMN IF NOT EXISTS quantidade_minima NUMERIC(15,3) CHECK (quantidade_minima BETWEEN 0 AND 999999999998.999);
CREATE TABLE IF NOT EXISTS compra_monitoramento (
    origem VARCHAR(20) NOT NULL,
    estoque_id BIGINT NOT NULL,
    abaixo BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY(origem,estoque_id)
);
CREATE TABLE IF NOT EXISTS compra_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem VARCHAR(20) NOT NULL CHECK(origem IN ('ALMOXARIFADO','MANUTENCAO','COMPRAS')),
    tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('ESTOQUE_MINIMO','SOLICITACAO_PECA','MANUAL')),
    estoque_id BIGINT,
    solicitacao_id BIGINT UNIQUE REFERENCES manutencao_chamado(id),
    item VARCHAR(150) NOT NULL,
    codigo VARCHAR(100),
    quantidade NUMERIC(15,3) NOT NULL CHECK(quantidade>0),
    unidade VARCHAR(5) NOT NULL DEFAULT 'un',
    fornecedor VARCHAR(150),
    valor_unitario NUMERIC(15,2),
    data_pedido DATE NOT NULL DEFAULT CURRENT_DATE,
    data_entrega DATE,
    status VARCHAR(30) NOT NULL CHECK(status IN ('Rascunho','Aguardando Aprovação','Aprovado','Reprovado','Recebido','Cancelado')),
    motivo VARCHAR(1000),
    solicitante VARCHAR(150),
    decidido_por BIGINT,
    decidido_nome VARCHAR(150),
    decidido_em TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    versao BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_compra_reposicao_aberta ON compra_pedido(origem,estoque_id) WHERE tipo='ESTOQUE_MINIMO' AND status IN ('Aguardando Aprovação','Aprovado');
CREATE INDEX IF NOT EXISTS ix_compra_origem ON compra_pedido(origem,id DESC);
