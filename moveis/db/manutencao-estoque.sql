CREATE TABLE IF NOT EXISTS manutencao_peca_estoque (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL CHECK (char_length(btrim(nome)) BETWEEN 2 AND 150),
 codigo VARCHAR(100) NOT NULL CHECK (char_length(btrim(codigo)) BETWEEN 1 AND 100),
 quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade>=0),
 unidade VARCHAR(5) NOT NULL CHECK (unidade IN ('un','kg','L','m','cx','par')),
 localizacao VARCHAR(100) NOT NULL CHECK (char_length(btrim(localizacao)) BETWEEN 2 AND 100),
 descricao VARCHAR(2000) NOT NULL DEFAULT '',
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_manutencao_peca_codigo ON manutencao_peca_estoque(upper(codigo));
CREATE TABLE IF NOT EXISTS manutencao_movimentacao_estoque (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 peca_id BIGINT NOT NULL REFERENCES manutencao_peca_estoque(id),
 tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('INICIAL','ENTRADA','SAIDA')),
 quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade>=0),
 saldo_anterior NUMERIC(15,3) NOT NULL CHECK (saldo_anterior>=0),
 saldo_posterior NUMERIC(15,3) NOT NULL CHECK (saldo_posterior>=0),
 chave_operacao UUID NOT NULL UNIQUE,
 criado_em TIMESTAMPTZ NOT NULL,
 responsavel_nome VARCHAR(150) NOT NULL,
 motivo VARCHAR(500) NOT NULL CHECK (char_length(btrim(motivo)) BETWEEN 3 AND 500),
 CONSTRAINT ck_manutencao_movimento_saldo CHECK (
  (tipo='INICIAL' AND saldo_anterior=0 AND saldo_posterior=quantidade)
  OR (tipo='ENTRADA' AND quantidade>0 AND saldo_posterior=saldo_anterior+quantidade)
  OR (tipo='SAIDA' AND quantidade>0 AND saldo_posterior=saldo_anterior-quantidade))
);
CREATE INDEX IF NOT EXISTS ix_manutencao_movimento_peca ON manutencao_movimentacao_estoque(peca_id,id DESC);
