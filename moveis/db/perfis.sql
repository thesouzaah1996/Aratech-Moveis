CREATE TABLE IF NOT EXISTS perfil_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_perfil_nome UNIQUE (nome)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_perfil_nome_ignore_case ON perfil_acesso (lower(nome));

CREATE TABLE IF NOT EXISTS funcionario_perfil_acesso (
    funcionario_id BIGINT NOT NULL REFERENCES funcionario(id),
    perfil_id BIGINT NOT NULL REFERENCES perfil_acesso(id),
    atribuido_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (funcionario_id, perfil_id)
);
