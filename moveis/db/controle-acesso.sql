CREATE TABLE IF NOT EXISTS registro_chegada (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nota_fiscal VARCHAR(44) NOT NULL, empresa VARCHAR(150) NOT NULL, nome_motorista VARCHAR(150) NOT NULL,
 placa VARCHAR(7) NOT NULL, descricao_carga VARCHAR(1000) NOT NULL, setor_responsavel VARCHAR(30) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO', chave_operacao UUID NOT NULL UNIQUE,
 data_chegada TIMESTAMPTZ NOT NULL, data_autorizacao TIMESTAMPTZ, data_entrada TIMESTAMPTZ, data_finalizacao TIMESTAMPTZ,
 CONSTRAINT ck_chegada_nf CHECK (nota_fiscal ~ '^[0-9]{1,44}$'),
 CONSTRAINT ck_chegada_placa CHECK (placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
 CONSTRAINT ck_chegada_empresa CHECK (char_length(btrim(empresa)) BETWEEN 2 AND 150),
 CONSTRAINT ck_chegada_motorista CHECK (char_length(btrim(nome_motorista)) BETWEEN 3 AND 150),
 CONSTRAINT ck_chegada_descricao CHECK (char_length(btrim(descricao_carga)) BETWEEN 3 AND 1000),
 CONSTRAINT ck_chegada_setor CHECK (setor_responsavel='ALMOXARIFADO'),
 CONSTRAINT ck_chegada_etapas CHECK (
   (status='AGUARDANDO' AND data_autorizacao IS NULL AND data_entrada IS NULL AND data_finalizacao IS NULL)
   OR (status='AUTORIZADO' AND data_autorizacao IS NOT NULL AND data_entrada IS NULL AND data_finalizacao IS NULL)
   OR (status='EM_RECEBIMENTO' AND data_autorizacao IS NOT NULL AND data_entrada IS NOT NULL AND data_finalizacao IS NULL)
   OR (status='FINALIZADO' AND data_autorizacao IS NOT NULL AND data_entrada IS NOT NULL AND data_finalizacao IS NOT NULL)),
 CONSTRAINT ck_chegada_horarios CHECK ((data_autorizacao IS NULL OR data_autorizacao>=data_chegada)
   AND (data_entrada IS NULL OR data_entrada>=data_autorizacao) AND (data_finalizacao IS NULL OR data_finalizacao>=data_entrada))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_chegada_nota_empresa ON registro_chegada (nota_fiscal,lower(empresa));
CREATE UNIQUE INDEX IF NOT EXISTS uk_chegada_placa_ativa ON registro_chegada (placa) WHERE status<>'FINALIZADO';
CREATE INDEX IF NOT EXISTS ix_chegada_fila ON registro_chegada (setor_responsavel,status,data_chegada,id);

ALTER TABLE registro_chegada DROP CONSTRAINT IF EXISTS ck_chegada_setor;
ALTER TABLE registro_chegada ADD CONSTRAINT ck_chegada_setor CHECK (setor_responsavel IN ('ALMOXARIFADO','CARREGAMENTO'));

ALTER TABLE registro_chegada ADD COLUMN IF NOT EXISTS tipo_operacao VARCHAR(15);
ALTER TABLE registro_chegada DROP CONSTRAINT IF EXISTS ck_chegada_operacao;
ALTER TABLE registro_chegada ADD CONSTRAINT ck_chegada_operacao CHECK (tipo_operacao IS NULL OR (setor_responsavel='CARREGAMENTO' AND tipo_operacao IN ('CARREGAR','DESCARREGAR')));
