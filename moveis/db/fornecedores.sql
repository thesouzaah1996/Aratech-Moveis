-- Tabela do cadastro de fornecedores; representante e um objeto de valor na mesma linha.
CREATE TABLE IF NOT EXISTS fornecedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    nome_normalizado VARCHAR(450) NOT NULL,
    email VARCHAR(150) NOT NULL,
    telefone VARCHAR(11) NOT NULL,
    nome_representante VARCHAR(150) NOT NULL,
    telefone_representante VARCHAR(11) NOT NULL,
    email_representante VARCHAR(150) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_fornecedor_nome UNIQUE (nome_normalizado),
    CONSTRAINT uk_fornecedor_email UNIQUE (email),
    CONSTRAINT ck_fornecedor_nome CHECK (char_length(btrim(nome)) BETWEEN 2 AND 150),
    CONSTRAINT ck_fornecedor_rep_nome CHECK (char_length(btrim(nome_representante)) BETWEEN 2 AND 150),
    CONSTRAINT ck_fornecedor_telefone CHECK (telefone ~ '^[0-9]{10,11}$'),
    CONSTRAINT ck_fornecedor_rep_telefone CHECK (telefone_representante ~ '^[0-9]{10,11}$')
);
