-- Rollback da estrutura de autorizacao descartada. Execute apos fazer backup.
-- Preserva nomes de perfis personalizados e todo o historico de estoque.
BEGIN;
DROP TABLE IF EXISTS usuario_perfil;
DROP TABLE IF EXISTS perfil_permissao;
ALTER TABLE IF EXISTS movimentacao_estoque DROP CONSTRAINT IF EXISTS movimentacao_estoque_responsavel_id_fkey;
DROP TABLE IF EXISTS usuario_acesso;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public'
               AND table_name='perfil_acesso' AND column_name='sistema') THEN
        DELETE FROM perfil_acesso WHERE sistema IS TRUE;
    END IF;
END $$;
ALTER TABLE IF EXISTS perfil_acesso DROP COLUMN IF EXISTS sistema;
ALTER TABLE IF EXISTS perfil_acesso DROP COLUMN IF EXISTS ativo;
CREATE TABLE IF NOT EXISTS perfil_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_perfil_nome UNIQUE (nome)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_perfil_nome_ignore_case ON perfil_acesso (lower(nome));
COMMIT;
