-- Categorias iniciais para o almoxarifado de uma fabrica de moveis.
-- Idempotente: preserva registros existentes e nao duplica nomes normalizados.
BEGIN;
-- Execute no banco do ambiente desejado antes de utilizar os endpoints de categorias.
-- O projeto nao aplica migracoes automaticamente.
CREATE TABLE IF NOT EXISTS categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    nome_normalizado VARCHAR(300) NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome_normalizado),
    CONSTRAINT ck_categoria_nome CHECK (char_length(btrim(nome)) BETWEEN 2 AND 100)
);

WITH dados(nome) AS (
    VALUES
    ('Chapas de MDF cru'),
    ('Chapas de MDF revestido'),
    ('Chapas de MDP cru'),
    ('Chapas de MDP revestido'),
    ('Compensados'),
    ('Madeira maciça'),
    ('Laminados decorativos'),
    ('Fitas de borda'),
    ('Lâminas de madeira'),
    ('Perfis de alumínio'),
    ('Parafusos'),
    ('Porcas'),
    ('Arruelas'),
    ('Buchas de fixação'),
    ('Cavilhas'),
    ('Conectores minifix'),
    ('Tambores de montagem'),
    ('Suportes de prateleira'),
    ('Cantoneiras'),
    ('Chapas de união'),
    ('Dobradiças'),
    ('Corrediças'),
    ('Puxadores'),
    ('Fechaduras'),
    ('Trilhos para portas'),
    ('Roldanas'),
    ('Rodízios'),
    ('Pés para móveis'),
    ('Sapatas niveladoras'),
    ('Amortecedores para portas'),
    ('Colas PVA'),
    ('Adesivos de contato'),
    ('Colas hot melt'),
    ('Selantes'),
    ('Vernizes'),
    ('Tintas'),
    ('Seladoras'),
    ('Thinners e solventes'),
    ('Lixas'),
    ('Massas para correção'),
    ('Brocas'),
    ('Fresas'),
    ('Discos de serra'),
    ('Ferramentas manuais'),
    ('Abrasivos para polimento'),
    ('Lubrificantes industriais'),
    ('Materiais de embalagem'),
    ('Proteção para transporte'),
    ('Equipamentos de proteção individual'),
    ('Materiais de limpeza industrial')
), inseridas AS (
    INSERT INTO categoria (nome, nome_normalizado, ativo)
    SELECT nome, lower(nome), true FROM dados
    ON CONFLICT (nome_normalizado) DO NOTHING
    RETURNING id
)
SELECT count(*) AS categorias_inseridas FROM inseridas;
COMMIT;
SELECT count(*) AS total_categorias, count(*) FILTER (WHERE ativo) AS categorias_ativas FROM categoria;
